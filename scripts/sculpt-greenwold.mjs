/**
 * A lane that ENDS on a place's own middle is a lane through the middle of it,
 * and the great oak of the Long Meadow, the well of Coldwake and the arch of
 * the Cellars all stood in the road the first time this ran. So a lane is cut
 * `back` metres short of its last point, and a waypoint that lands on a place
 * is pushed `off` metres to one side of it.
 */
function stopShort(pts, back) {
  const total = polyLength(pts);
  const p = polyAt(pts, Math.max(0, total - back));
  const keep = [];
  let run = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    keep.push(pts[i]);
    run += Math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]);
    if (run >= total - back) break;
  }
  keep.push([r2(p.x), r2(p.z)]);
  return keep;
}
/** Push any waypoint within `near` of a point out to `off` metres from it. */
function stepAside(pts, at, near, off) {
  return pts.map(([x, z]) => {
    const d = Math.hypot(x - at.x, z - at.z);
    if (d > near) return [x, z];
    const a = d > 1e-6 ? { x: (x - at.x) / d, z: (z - at.z) / d } : { x: 0, z: 1 };
    return [r2(at.x + a.x * off), r2(at.z + a.z * off)];
  });
}
