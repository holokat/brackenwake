const SPACES = {};
function space(id, name, at, radius, note) {
  const s = {
    id, name, note,
    at: { x: r2(at.x), z: r2(at.z) },
    radius,
    pieces: [], runs: [], areas: [], people: [], spawns: [],
    trees: [], rocks: [], markers: [],
  };
  SPACES[id] = s;
  return s;
}
const rel = (s, x, z) => ({ x: r2(x - s.at.x), z: r2(z - s.at.z) });
/**
 * The largest radius at a point that leaves every space already standing alone.
 *
 * The named places, the nine stones and the fields have radii their own
 * contents fix, so they go down first and keep them. Everything with give in it
 * (the stretches of road, the copses, the willow banks) is sized by this, which
 * is why the report's worst overlap can be a measurement and not a hope.
 */
function fitRadius(x, z, want, floor = 40) {
  let r = want;
  for (const o of Object.values(SPACES)) {
    const d = Math.hypot(x - o.at.x, z - o.at.z);
    r = Math.min(r, d - o.radius - 6);
  }
  return Math.max(floor, Math.round(Math.min(want, r)));
}
const addPiece = (s, model, x, z, yaw = 0, extra = {}) => { s.pieces.push({ model, ...rel(s, x, z), yaw: r2(norm360(yaw)), ...extra }); };
/**
 * A piece put down at a point, or at the nearest clear point to it.
 *
 * A fingerpost dropped at a fork lands wherever the fork is, and the first run
 * put one inside a willow. The schema refuses that, and rightly, so this asks
 * the schema's own `rectsOverlap` about every piece already in the space and
 * walks outward until it finds room. It answers where the piece really went,
 * or null when there was nowhere, so the report can say so.
 */
function addPieceClear(s, model, x, z, yaw = 0) {
  for (const step of [0, 5, 9, 14, 20]) {
    for (let i = 0; i < (step ? 12 : 1); i++) {
      const a = (i / 12) * Math.PI * 2;
      const at = rel(s, x + Math.sin(a) * step, z + Math.cos(a) * step);
      if (Math.hypot(at.x, at.z) > s.radius - 3) continue;
      const want = rectOf({ model, x: at.x, z: at.z, yaw });
      if (!want) return null;
      if (s.pieces.some((q) => rectsOverlap(want, rectOf(q)))) continue;
      s.pieces.push({ model, x: at.x, z: at.z, yaw: r2(norm360(yaw)) });
      return at;
    }
  }
  return null;
}
const addRock = (s, kind, x, z, yaw = 0, scale = 1) => { s.rocks.push({ kind, ...rel(s, x, z), yaw: r2(norm360(yaw)), scale: r2(scale) }); };
const addTree = (s, species, x, z, yaw, scale) => { s.trees.push({ species, ...rel(s, x, z), yaw: r2(norm360(yaw)), scale: r2(scale) }); };
const addMarker = (s, label, note, kind, x, z) => { s.markers.push({ ...rel(s, x, z), label, note, kind }); };
const addSpawn = (s, id, x, z, night = false) => { const row = { id, ...rel(s, x, z) }; if (night) row.night = true; s.spawns.push(row); };
const addPerson = (s, role, x, z, yaw) => { s.people.push({ name: null, role, ...rel(s, x, z), yaw: r2(norm360(yaw)) }); };

/**
 * One of the nine plans, copied to a point and turned.
 *
 * Two things change on the way and both are the schema's doing. The `place`
 * becomes an `at`, and every PERSON NAME is dropped: `plan_schema` refuses a
 * named villager in a space, because `PERSON.bram.place` is "hearthhome" and a
 * space stands at a point and has no place at all. The ROLE is kept, so the
 * game still stands an innkeeper in the inn, and `castMarkers` puts a marker
 * beside each of the cast so nobody has to guess who the plan meant.
 */
function fromPlan(planId, id, name, at, deg = 0, radius = null) {
  const p = planOf(planId);
  const R = rotBy(deg);
  const s = space(id, name, at, radius || p.radius, p.notes);
  s.pieces = (p.pieces || []).map((q) => ({ ...q, ...R(q.x, q.z), yaw: r2(norm360((q.yaw || 0) + deg)) }));
  s.runs = (p.runs || []).map((r) => ({ ...r, from: R(r.from.x, r.from.z), to: R(r.to.x, r.to.z) }));
  s.areas = (p.areas || []).map((a) => ({ ...a, points: a.points.map(([x, z]) => { const q = R(x, z); return [q.x, q.z]; }) }));
  s.people = (p.people || []).map((q) => ({ ...q, name: null, ...R(q.x, q.z), yaw: r2(norm360((q.yaw || 0) + deg)) }));
  s.spawns = (p.spawns || []).map((q) => ({ ...q, ...R(q.x, q.z) }));
  if (p.arrival) s.arrival = { ...R(p.arrival.x, p.arrival.z), yaw: r2(norm360((p.arrival.yaw || 0) + deg)) };
  return s;
}
