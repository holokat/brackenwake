//
// The level is NOT a number typed here. At every 60 m down the river the
// ground is asked what it is, the water is put two and a half metres under it,
// and then the whole profile is forced to fall: never above the target line
// from the head to 2 m at the east edge, and never higher than the point
// upstream. So the river is in a cut the whole way on ground nobody guessed
// at, and it runs one way.
const RIVER_STEP = 60;
/**
 * Every vertex of the river, and no gap longer than `step` between them.
 *
 * `polySamples` walks a fixed arc step, which SKIPS THE CORNERS, and the first
 * run measured it: at s = 400 the guide's river turns hard and the two straight
 * ribbons either side of the turn left a dry notch on the outside of the bend,
 * so one of the fifty nine points on the centreline had no water in it. A
 * ribbon is a straight capsule; the samples have to include the bends.
 */
function riverSamples(pts, step) {
  const out = [];
  let run = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    const [ax, az] = pts[i], [bx, bz] = pts[i + 1];
    const seg = Math.hypot(bx - ax, bz - az);
    const parts = Math.max(1, Math.ceil(seg / step));
    const tx = seg > 1e-9 ? (bx - ax) / seg : 1, tz = seg > 1e-9 ? (bz - az) / seg : 0;
    for (let k = 0; k < parts; k++) {
      const t = k / parts;
      out.push({ x: ax + (bx - ax) * t, z: az + (bz - az) * t, tx, tz, s: run + seg * t });
    }
    run += seg;
  }
  const last = pts[pts.length - 1];
  out.push({ x: last[0], z: last[1], tx: 1, tz: 0, s: run });
  return out;
}
