/**
 * The pieces a space is allowed to stand in water, and every one of them is a
 * thing that is only itself when it is wet.
 */
const WET_ON_PURPOSE = new Set([
  'stone_bridge_10m', 'footbridge', 'stepping_stones', 'eel_weir', 'mill_wheel',
  'chapel_sunken', 'rowing_boat_rotten', 'lily_pad_patch', 'willow',
  'headstone_a', 'headstone_b', 'headstone_c', 'headstone_d', 'headstone_e',
]);
/** The rock kinds that belong in the shallows. */
const WET_ROCKS = new Set(['reed_bed', 'dew_pond']);
/**
 * Anything standing in the water that has no business there, walked ashore.
 *
 * The village's hay rick came out of the plan at local 43, -12 and the new
 * channel runs under it: a rick in a river is exactly the kind of thing that
 * ships because the code that placed it was right and the ground it landed on
 * was not. Each one is walked outward in five metre rings until the sample is
 * dry, and dropped if there is no dry ground inside twenty five metres. What
 * moved and what went is counted and said.
 */
function dryOff(s) {
  const moved = [], gone = [];
  const wet = (x, z) => sampleAt(s.at.x + x, s.at.z + z).water;
  const walk = (q, allow) => {
    if (allow.has(q.model || q.kind)) return true;
    if (!wet(q.x, q.z)) return true;
    for (const step of [5, 10, 15, 20, 25]) {
      for (let i = 0; i < 12; i++) {
        const a = (i / 12) * Math.PI * 2;
        const x = r2(q.x + Math.sin(a) * step), z = r2(q.z + Math.cos(a) * step);
        if (Math.hypot(x, z) > s.radius - 3 || wet(x, z)) continue;
        moved.push(`${q.model || q.kind} ${step} m`);
        q.x = x; q.z = z;
        return true;
      }
    }
    gone.push(q.model || q.kind);
    return false;
  };
  // A piece has a footprint, and a walked piece lands in its neighbour's (the
  // hay rick walked into the stable): a wet piece is dropped and said, never
  // walked. Rocks and trees have no footprint and still walk.
  s.pieces = s.pieces.filter((q) => { if (WET_ON_PURPOSE.has(q.model) || !wet(q.x, q.z)) return true; gone.push(q.model); return false; });
  s.rocks = s.rocks.filter((q) => walk(q, WET_ROCKS));
  s.trees = s.trees.filter((q) => walk(q, new Set(['willow'])));
  // and nothing a space places may stand beyond its own reach: the schema
  // refuses it, so it is dropped here and counted, not left for the audit
  for (const list of ['pieces', 'rocks', 'trees', 'spawns', 'people', 'markers']) {
    const before = (s[list] || []).length;
    s[list] = (s[list] || []).filter((q) => Math.hypot(q.x, q.z) <= s.radius - 1);
    for (let i = before; i > s[list].length; i--) gone.push(`${list.slice(0, -1)} beyond ${s.radius} m`);
  }
  return { moved, gone };
}

/**
 * Every run in a space that the river goes through, dropped.
 *
 * Hearthhome's flint wall is a closed ring and the river now crosses it. A wall
 * standing in a river is the thing this project keeps having to catch: the code
 * that placed it was right and the path it took was not. So the crossed runs
 * come out, which leaves a water gate, and the number is reported.
 */
function openTheWall(s) {
  const kept = [];
  let dropped = 0;
  for (const r of s.runs) {
    const a = { x: s.at.x + r.from.x, z: s.at.z + r.from.z };
    const b = { x: s.at.x + r.to.x, z: s.at.z + r.to.z };
    let wet = false;
    const n = Math.max(2, Math.ceil(Math.hypot(b.x - a.x, b.z - a.z) / 2));
    for (let i = 0; i <= n; i++) {
      const x = lerp(a.x, b.x, i / n), z = lerp(a.z, b.z, i / n);
      const hit = riverNear(x, z);
      if (hit.d < riverWidth(hit.arc) / 2 + 2) { wet = true; break; }
    }
    if (wet) dropped++; else kept.push(r);
  }
  s.runs = kept;
  return dropped;
}

