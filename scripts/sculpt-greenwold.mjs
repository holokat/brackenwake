// The Greenwold, sculpted to the painted map, by script.
// Run: node scripts/sculpt-greenwold.mjs
//
// WHY A SCRIPT AND NOT THE EDITOR. The painting is one image and the realm is
// nineteen square kilometres. Laying four thousand strokes and fifty spaces by
// hand is a fortnight; laying them from the same twelve coordinates the guide
// already holds is an afternoon, and then the editor is left for the part a
// person is better at, which is walking it and moving what is wrong.
//
// IT IS RERUNNABLE AND IT OVERWRITES:
//
//   public/terrain/greenwold.json     the whole stroke list. The header stays
//                                     what it was: sculpt, a flat 6 m grass
//                                     world, no sea, and `places: false`, which
//                                     is what puts the sheet's own nine
//                                     authored sites away (field.js line 793)
//                                     so the spaces below are the only Greenwold
//                                     and there is not a second village.
//   src/mmo/spaces/greenwold_*.json   one space per place, field, wood, copse,
//                                     bank and stretch of road
//   src/mmo/spaces/list.js            regenerated by tools/editor_save.mjs's own
//                                     writeSpaceIndex, through the same
//                                     saveEditorFile the editor posts to, so
//                                     this is the editor's path and not a
//                                     second one
//
// It does not touch the three `tile_*` spaces the user's own editor made, and
// it does not touch zones.js, the guide, the map or the minimap.
//
// ---- where the numbers come from -------------------------------------------
//
// `src/mmo/greenwold_guide.js` is the painting measured, and it is the ONE
// source: the twelve centres, the ring, the two roads and the river all come
// off GUIDE_ZONES, GUIDE_ROADS and GUIDE_RIVER. Nothing here re-derives an
// image fraction. The guide's own frame is the important part and is easy to
// get backwards: NORTH IS MINUS Z, so the top of the sheet is z = -2200, the
// chalk hills are at NEGATIVE z, and Coldwake, south west on the sheet, is at
// x -796, z +1291.
//
// ---- how a plan is put on the water ----------------------------------------
//
// Three of the nine plans are drawn about water: Hearthhome about its bridge,
// the Mill Run about its leat, and the Old Cellars about a bank. The guide's
// river runs straight through all three centres, which would put the well, the
// mill and the arch in the water. So those three spaces are not placed at the
// guide's point. They are placed so that the PART OF THE PLAN THAT WANTS WATER
// lands on the guide's river, exactly, and the buildings step back off it:
//
//   Hearthhome   turned until the bridge's 10 m span is square to the river,
//                then moved so the bridge stands on the guide's own waypoint
//   the Mill Run turned until the plan's leat runs with the river, then moved
//                so the middle of the leat is the river's own line
//   the Cellars  moved 45 m onto the north bank, off the channel
//
// So the river is the guide's polyline to the metre and the plan is what moved.
// The village's flint wall is a closed ring and the river now crosses it: the
// runs the water goes through are DROPPED from the space, which leaves a water
// gate, and the report counts them.
//
// ---- the order of the strokes is the picture -------------------------------
//
//   1  the downland skeleton: a grid of plateaus at a target height, because a
//      plateau pulls the ground TO a number where a raise only adds one
//   2  the chalk hills, as mountains and ridges laid over that skeleton
//   3  roughening
//   4  the Standing Hedge's rise and the Long Meadow's
//   5  the river's corridor, cut as plateaus to the water plus a bank. The
//      water level at each point is MEASURED off the ground there and then
//      forced to fall, so the river runs downhill on ground nobody guessed at
//   6  the flats: the village, the water meadows, Coldwake, the camp, the stones
//   7  the water: the river, the weir at the mill, the mere, the ponds
//   8  the scar and the hollow, cut with pit and cliff
//   9  the paint: the fields, the lanes, the Kingsroad, the scar, the mud
//
// Everything the report claims it measured through `createWorldField` with the
// list on it, which is the field the game meshes chunks from.

