// ---------------------------------------------------------------- the dice --
//
// One seed, and every random number comes off it in a fixed order, so two runs
// write two identical files and the diff of a rerun is empty.
const SEED = 20260907;
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rng = mulberry32(SEED);
const rand = (lo, hi) => lo + rng() * (hi - lo);

/** Value noise, for the roll of the downland. Deterministic, and no tables. */
function hash2(ix, iz, s) {
  let h = Math.imul(ix | 0, 374761393) ^ Math.imul(iz | 0, 668265263) ^ Math.imul(s | 0, 2246822519);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
function vnoise(x, z, wave, s) {
  const fx = x / wave, fz = z / wave;
  const ix = Math.floor(fx), iz = Math.floor(fz);
  const tx = fx - ix, tz = fz - iz;
  const sx = tx * tx * (3 - 2 * tx), sz = tz * tz * (3 - 2 * tz);
  const a = hash2(ix, iz, s), b = hash2(ix + 1, iz, s);
  const c = hash2(ix, iz + 1, s), d = hash2(ix + 1, iz + 1, s);
  return (a + (b - a) * sx) * (1 - sz) + (c + (d - c) * sx) * sz;
}

// ------------------------------------------------------------- the geometry --

const r2 = (v) => Math.round(v * 100) / 100;
const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);
const smoothstep = (e0, e1, v) => { const t = clamp01((v - e0) / (e1 - e0 || 1e-9)); return t * t * (3 - 2 * t); };
const norm360 = (d) => ((d % 360) + 360) % 360;
const lerp = (a, b, t) => a + (b - a) * t;
const D2R = Math.PI / 180;

/**
 * The plan frame's own turn, and it is the schema's turn and not a new one:
 * `plan_schema.cornersOf` maps a local offset (x, z) at yaw `a` to
 * (x cos a + z sin a, z cos a - x sin a), so a plan rotated by `deg` is every
 * point through this and every yaw plus `deg`.
 */
function rotBy(deg) {
  const a = deg * D2R, c = Math.cos(a), s = Math.sin(a);
  return (x, z) => ({ x: r2(x * c + z * s), z: r2(z * c - x * s) });
}
/** The world direction the local +x axis (a run's own length) points at. */
const spanDir = (deg) => ({ x: Math.cos(deg * D2R), z: -Math.sin(deg * D2R) });
/** The world direction the local +z axis points at. */
const alongDir = (deg) => ({ x: Math.sin(deg * D2R), z: Math.cos(deg * D2R) });

function segDist(px, pz, ax, az, bx, bz) {
  const dx = bx - ax, dz = bz - az;
  const len2 = dx * dx + dz * dz;
  let t = 0;
  if (len2 > 1e-12) t = clamp01(((px - ax) * dx + (pz - az) * dz) / len2);
  const ex = ax + dx * t - px, ez = az + dz * t - pz;
  return { d: Math.hypot(ex, ez), t };
}
/** Distance to a polyline, and the arc length at the nearest point on it. */
function polyDist(pts, x, z) {
  let best = Infinity, arc = 0, run = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    const [ax, az] = pts[i], [bx, bz] = pts[i + 1];
    const seg = Math.hypot(bx - ax, bz - az);
    const hit = segDist(x, z, ax, az, bx, bz);
    if (hit.d < best) { best = hit.d; arc = run + hit.t * seg; }
    run += seg;
  }
  return { d: best, arc, total: run };
}
const polyLength = (pts) => { let n = 0; for (let i = 0; i + 1 < pts.length; i++) n += Math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]); return n; };
/** The point `s` metres along a polyline, and the unit tangent there. */
function polyAt(pts, s) {
  let run = 0;
  for (let i = 0; i + 1 < pts.length; i++) {
    const [ax, az] = pts[i], [bx, bz] = pts[i + 1];
    const seg = Math.hypot(bx - ax, bz - az);
    if (run + seg >= s || i + 2 === pts.length) {
      const t = seg > 1e-9 ? clamp01((s - run) / seg) : 0;
      const L = seg || 1;
      return { x: ax + (bx - ax) * t, z: az + (bz - az) * t, tx: (bx - ax) / L, tz: (bz - az) / L, s };
    }
    run += seg;
  }
  const [x, z] = pts[pts.length - 1];
  return { x, z, tx: 1, tz: 0, s };
}
function polySamples(pts, step) {
  const total = polyLength(pts);
  const n = Math.max(1, Math.round(total / step));
  const out = [];
  for (let i = 0; i <= n; i++) out.push({ ...polyAt(pts, (i / n) * total), total });
  return out;
}
/** Whether a point is inside a convex quad. */
function inQuad(x, z, q) {
  let sign = 0;
  for (let i = 0; i < 4; i++) {
    const [ax, az] = q[i], [bx, bz] = q[(i + 1) % 4];
    const c = (bx - ax) * (z - az) - (bz - az) * (x - ax);
    if (c === 0) continue;
    const s = c > 0 ? 1 : -1;
    if (sign === 0) sign = s; else if (s !== sign) return false;
  }
  return true;
}

