function plantable(x, z, keepRoad = 6, keepWater = 8) {
  if (roadNear(x, z).d < keepRoad) return false;
  const r = riverNear(x, z);
  if (r.d < riverWidth(r.arc) / 2 + keepWater) return false;
  if (inAnyField(x, z)) return false;
  if (Math.hypot(x - VILLAGE.centre.x, z - VILLAGE.centre.z) < 70) return false;
  if (Math.hypot(x - AT.sunkenchapel.x, z - AT.sunkenchapel.z) < 128) return false;
  for (const p of PONDS) if (Math.hypot(x - p.x, z - p.z) < 26) return false;
  if (Math.hypot(x - MILL_POND.x, z - MILL_POND.z) < 20) return false;
  return true;
}
/**
 * A jittered grid with rejection. The spacing is a FLOOR and not an average,
 * so "six to nine metres apart" is a claim the closest pair in the report can
 * be held to.
 */
function scatter(s, species, cx, cz, rInner, rOuter, step, minGap, opts = {}) {
  const placed = [];
  for (let gz = -rOuter; gz <= rOuter; gz += step) {
    for (let gx = -rOuter; gx <= rOuter; gx += step) {
      const x = cx + gx + rand(-step * 0.28, step * 0.28);
      const z = cz + gz + rand(-step * 0.28, step * 0.28);
      const d = Math.hypot(x - cx, z - cz);
      if (d < rInner || d > rOuter) continue;
      if (Math.hypot(x - s.at.x, z - s.at.z) > s.radius - 2) continue;
      if (!plantable(x, z, opts.keepRoad ?? 6, opts.keepWater ?? 8)) continue;
      let tooClose = false;
      for (const p of placed) if (Math.hypot(p[0] - x, p[1] - z) < minGap) { tooClose = true; break; }
      if (tooClose) continue;
      placed.push([x, z]);
      addTree(s, typeof species === 'function' ? species() : species, x, z, rand(0, 360), rand(opts.lo ?? 0.85, opts.hi ?? 1.3));
    }
  }
  return placed.length;
}

