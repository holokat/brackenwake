// Every craftable item the recipes make, grouped by family and result, with
// the material variants, the skill and station, the difficulty range, whether
// the result really lands as an items.js base (win_crafting.resultBaseFor) and
// whether that base has a painting. Written to docs/mmo/16-CRAFTABLES.md so the
// list is a file and not a memory.  node scripts/list-craftables.mjs
import fs from 'node:fs';
import { RECIPES, FORAGE_RECIPES, STATIONS } from '../src/mmo/recipes.js';
import { BASES } from '../src/mmo/items.js';
import { SKILLS } from '../src/mmo/skills.js';
import { resultBaseFor, unmakeableReason } from '../src/game/win_crafting.js';
import { ITEM_ICONS } from '../src/game/icon_art.js';

const skillName = Object.fromEntries(SKILLS.map((s) => [s.id, s.name]));
const stationName = (id) => (Array.isArray(STATIONS) ? STATIONS.find((s) => s.id === id)?.name : STATIONS?.[id]?.name) || id;
const words = (s) => String(s || '').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/_/g, ' ').toLowerCase();

const FAMILY_TITLE = {
  weapon: 'Weapons', armour: 'Armour', shield: 'Shields', staff: 'Staves', bow: 'Bows', ammo: 'Ammunition',
  potion: 'Potions (alchemy)', meal: 'Meals (kitchen)', tool: 'Tools', bag: 'Bags', scroll: 'Scrolls',
  forageMeal: 'Forage meals (kitchen)', foragePotion: 'Forage draughts (alchemy)',
};

const groups = new Map();
for (const r of [...RECIPES, ...FORAGE_RECIPES]) {
  const key = `${r.family}:${r.result.base}`;
  const g = groups.get(key) || { family: r.family, resultId: r.result.base, base: resultBaseFor(r), reason: unmakeableReason(r), recipes: [] };
  g.recipes.push(r);
  groups.set(key, g);
}

const rows = [...groups.values()].map((g) => {
  const base = g.base ? BASES[g.base] : null;
  const name = base ? base.name : g.recipes[0].name.replace(/^\w+ /, '');
  const mats = [...new Set(g.recipes.map((r) => r.result.material).filter(Boolean))];
  const diffs = g.recipes.map((r) => r.difficulty);
  const skills = [...new Set(g.recipes.map((r) => r.skill))].map((s) => skillName[s] || s);
  const stations = [...new Set(g.recipes.map((r) => r.station))].map(stationName);
  const ingredients = [...new Set(g.recipes.flatMap((r) => Object.keys(r.materials || {})))].map(words);
  return {
    family: g.family, title: FAMILY_TITLE[g.family] || g.family, resultId: g.resultId, base: g.base, name: base ? base.name : g.recipes[0].name,
    variants: g.recipes.length, materials: mats, min: Math.min(...diffs), max: Math.max(...diffs), skills, stations, ingredients,
    painted: !!(g.base && ITEM_ICONS[g.base]), reason: g.reason, buff: g.recipes[0].buff || g.recipes[0].result.buff || null,
  };
});

const order = Object.keys(FAMILY_TITLE);
rows.sort((a, b) => order.indexOf(a.family) - order.indexOf(b.family) || a.min - b.min);

let md = `# Every craftable item\n\nGenerated by \`scripts/list-craftables.mjs\` from \`src/mmo/recipes.js\`, \`src/mmo/items.js\` and \`src/game/win_crafting.js\`. ${RECIPES.length + FORAGE_RECIPES.length} recipes make ${rows.length} distinct results. A "variant" is one recipe: a longsword has one per metal. "Lands as" is the items.js base the crafting panel really hands over; a result with none is greyed in the panel with the reason shown.\n\n`;
let cur = null;
for (const r of rows) {
  if (r.title !== cur) { cur = r.title; md += `\n## ${cur}\n\n| result | variants | materials | skill | station | difficulty | lands as | painted |\n|---|---|---|---|---|---|---|---|\n`; }
  md += `| ${r.name} | ${r.variants} | ${r.materials.map(words).join(', ') || r.ingredients.join(', ')} | ${r.skills.join(', ')} | ${r.stations.join(', ')} | ${r.min === r.max ? r.min : r.min + ' to ' + r.max} | ${r.base ? r.base : 'nothing: ' + r.reason} | ${r.painted ? 'yes' : (r.base ? 'NO' : '')} |\n`;
}
const unpainted = rows.filter((r) => r.base && !r.painted);
const dead = rows.filter((r) => !r.base);
md += `\n## What still needs a painting\n\n${unpainted.length ? unpainted.map((r) => `- ${r.name} (\`${r.base}\`)`).join('\n') : 'Nothing: every craftable result that lands has a painting.'}\n\n## Recipes with nowhere to land\n\n${dead.map((r) => `- ${r.name}: ${r.reason}`).join('\n')}\n`;
fs.writeFileSync('docs/mmo/16-CRAFTABLES.md', md);
fs.writeFileSync(process.argv[2] || '/dev/null', JSON.stringify({ rows, counts: { recipes: RECIPES.length + FORAGE_RECIPES.length, results: rows.length, unpainted: unpainted.length, dead: dead.length } }));
console.log(`${RECIPES.length + FORAGE_RECIPES.length} recipes, ${rows.length} results, ${unpainted.length} unpainted, ${dead.length} with nowhere to land -> docs/mmo/16-CRAFTABLES.md`);
